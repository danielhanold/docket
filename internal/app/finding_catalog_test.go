// -update rewrites testdata/finding-catalog.txt from the current finding text,
// following the internal/harness golden pattern: a deliberate wording change
// becomes a reviewable diff of one file rather than a hand edit. It is never
// set in CI.
var updateCatalog = flag.Bool("update", false, "rewrite testdata/finding-catalog.txt from the current finding text")

const findingCatalogPath = "testdata/finding-catalog.txt"

// catalogFrontmatterShapes is one source per frontmatter-repair shape
// PlanRepairs words (the same seven shapes TestRepairFindingsCarryThreeParts
// pins in package reposetup), each rendered as the check would print it.
func catalogFrontmatterShapes() []struct {
	name     string
	src      string
	archived bool
} {
	fm := func(extra string) string {
		return "---\nid: 1\nslug: wisdom-ai-bastion\nstatus: done\ntitle: T\ntype: feature\n" + extra + "---\n\nBody.\n"
	}
	claimed := fm("claimed_at: 2026-05-20T10:00:00Z\n")
	return []struct {
		name     string
		src      string
		archived bool
	}{
		{"drop-final-claimed-at", claimed, true},
		{"quote-unsafe-scalar", strings.Replace(fm(""), "title: T", "title: yes", 1), false},
		{"scalar-to-list", fm("depends_on: 3, 4\n"), false},
		{"ambiguous value", strings.Replace(fm(""), "title: T", "title: true", 1), false},
		{"non-id list", fm("related: foo\n"), false},
		{"claimed_at, not done", strings.Replace(claimed, "status: done", "status: proposed", 1), true},
		{"undecodable", "---\nid: 1\nid: 2\n---\nbody\n", false},
	}
}

func catalogKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// renderFindingCatalog renders every check and status finding message docket
// can print, section by section, so one file shows the whole vocabulary for
// review. Every map is walked in sorted key order so the bytes are stable.
func renderFindingCatalog(t *testing.T) string {
	t.Helper()
	var b strings.Builder
	b.WriteString("# Generated by TestFindingCatalogGolden -update (internal/app/finding_catalog_test.go); do not hand-edit.\n")
	b.WriteString("# Every repository check and status finding message, rendered from its producer.\n")

	b.WriteString("\n## Check header\n\n")
	sample := []reposetup.Finding{{Severity: reposetup.SeverityError}, {Severity: reposetup.SeverityWarning}}
	states := stateConstants(t)
	sort.Strings(states)
	for _, s := range states {
		b.WriteString(checkHeader(s, sample) + "\n")
	}
	b.WriteString(checkHeader(string(reposetup.StateHealthy), nil) + "\n")

	b.WriteString("\n## Validator findings\n")
	dotDocket := reposetup.RecordLocator{Checkout: ".docket"}
	fixtures := validationFixtures()
	for _, code := range catalogKeys(validationCodeSet(t)) {
		fxs := fixtures[code]
		if len(fxs) == 0 {
			t.Fatalf("validator code %q has no fixture in validationFixtures", code)
		}
		for _, fx := range fxs {
			text := explainValidation(fx.finding, dotDocket)
			fmt.Fprintf(&b, "\n### %s — %s (%s)\n", code, fx.label, fx.finding.Severity)
			fmt.Fprintf(&b, "%s\n%s\nremedy: %s\n", text.Message, text.Impact, text.Remedy)
		}
	}

	b.WriteString("\n## Remedy locations by layout\n")
	locators := []struct {
		name string
		loc  reposetup.RecordLocator
	}{
		{"shared checkout", dotDocket},
		{"private checkout path", reposetup.RecordLocator{Checkout: "/home/u/.local/share/dckt/o/r/checkouts/r-1a2b3c4d"}},
		{"private checkout in words", reposetup.RecordLocator{Label: "your private metadata checkout"}},
		{"no resolved layout", reposetup.RecordLocator{}},
	}
	for _, l := range locators {
		fmt.Fprintf(&b, "\n### %s\nremedy: %s\n", l.name, explainValidation(danglingDep(), l.loc).Remedy)
	}

	b.WriteString("\n## Frontmatter-repair findings\n")
	rel := "docs/changes/archive/2026-05-28-0001-wisdom-ai-bastion.md"
	for _, shape := range catalogFrontmatterShapes() {
		rfs, err := reposetup.PlanRepairs(rel, []byte(shape.src), shape.archived, dotDocket)
		if err != nil {
			t.Fatalf("PlanRepairs(%s): %v", shape.name, err)
		}
		fmt.Fprintf(&b, "\n### %s\n", shape.name)
		for _, f := range reposetup.EvaluateHealth(reposetup.Classification{State: reposetup.StateHealthy}, reposetup.Facts{}, rfs) {
			if f.Repairable != nil {
				appendFindingBlock(&b, f)
			}
		}
		b.WriteString("\n")
	}

	b.WriteString("\n## Generated-view findings\n")
	derived := derivedScenarioFindings(t)
	for _, code := range catalogKeys(derived) {
		appendFindingBlock(&b, derived[code])
	}
	appendFindingBlock(&b, corpusUnreadableFinding(errors.New("object 4b825dc6 is missing")))
	b.WriteString("\n")

	// A setup that is not healthy re-words every record remedy
	// (checkRecordLocator): the checkout may not exist and repair refuses.
	b.WriteString("\n## Record remedies while setup is not healthy\n")
	blocked := checkRecordLocator(layout.Layout{}, reposetup.StateNeedsReview)
	fmt.Fprintf(&b, "\n### validator (%s)\nremedy: %s\n", danglingDep().Code, explainValidation(danglingDep(), blocked).Remedy)
	for _, shape := range catalogFrontmatterShapes() {
		rfs, err := reposetup.PlanRepairs(rel, []byte(shape.src), shape.archived, blocked)
		if err != nil {
			t.Fatalf("PlanRepairs(%s): %v", shape.name, err)
		}
		for _, f := range rfs {
			fmt.Fprintf(&b, "\n### %s — %s\nremedy: %s\n", f.FindingCode(), shape.name, f.Remedy)
		}
	}
	blockedDerived := map[string]string{}
	for _, corpus := range derivedScenarios(t) {
		corpus.locator = blocked
		for _, df := range derivedViewFindings(derivedTestConfig(), corpus) {
			if _, ok := blockedDerived[df.Code]; !ok {
				blockedDerived[df.Code] = df.Finding().Remedy
			}
		}
	}
	for _, code := range catalogKeys(blockedDerived) {
		fmt.Fprintf(&b, "\n### %s\nremedy: %s\n", code, blockedDerived[code])
	}

	b.WriteString("\n## Status parse findings\n")
	_, parsed := parseCorpusAt(catalogUnparseableBlobs(), dotDocket)
	for _, f := range parsed {
		fmt.Fprintf(&b, "\n- [%s] %s (%s)\n  %s\n  %s\n  remedy: %s\n", f.Severity, f.Code, f.Path, f.Message, f.Impact, f.Remedy)
	}
	b.WriteString("\n")
	return b.String()
}

// catalogUnparseableBlobs is one record per parse-failure shape `docket
// status` words: an undecodable frontmatter and unpaired block markers in a
// change, and an undecodable ADR.
func catalogUnparseableBlobs() []StatusBlob {
	return []StatusBlob{
		{Kind: repository.KindChange, Path: "docs/changes/active/0001-dup.md", Data: []byte("---\nid: 1\nid: 2\n---\nbody\n")},
		{Kind: repository.KindChange, Path: "docs/changes/active/0002-markers.md", Data: []byte("---\nid: 2\n---\n\n## Artifacts\n\n<!-- docket:artifacts:start -->\n- x\n")},
		{Kind: repository.KindADR, Path: "docs/adrs/0003-yaml.md", Data: []byte("---\nid: [3\n---\nbody\n")},
	}
}

// TestFindingCatalogGolden keeps testdata/finding-catalog.txt, one reviewable
// file holding every check and status finding message, byte for byte in step
// with the producers. Regenerate it after a deliberate wording change with
// `go test -count=1 ./internal/app/ -run TestFindingCatalogGolden -update`.
//
// The population floor runs before the comparison, so a catalog that silently
// lost a section's findings fails even when regenerated. Mutation probe: drop
// one non-repairable frontmatter shape from catalogFrontmatterShapes — the
// frontmatter-manual-review floor must redden.
func TestFindingCatalogGolden(t *testing.T) {
	got := renderFindingCatalog(t)

	floor := []string{
		string(reposetup.RepairQuoteScalar), string(reposetup.RepairScalarToList), string(reposetup.RepairDropClaimedAt),
		reposetup.CodeFrontmatterManualReview,
		reposetup.CodeBoardStale, reposetup.CodeADRIndexStale,
		reposetup.CodeArtifactLinksStale, reposetup.CodeArtifactLinksMissing, reposetup.CodeArtifactLinksMalformed,
		reposetup.CodeArtifactBacklinkStale, reposetup.CodeArtifactBacklinkMalformed, reposetup.CodeArtifactBacklinkShared,
		reposetup.CodeCorpusUnreadable,
	}
	for _, code := range floor {
		if !strings.Contains(got, "] "+code) {
			t.Errorf("catalog has no %q finding block", code)
		}
	}
	if n := strings.Count(got, "] "+reposetup.CodeFrontmatterManualReview+" "); n < 4 {
		t.Errorf("catalog has %d %s blocks, want at least 4 (one per non-repairable frontmatter shape)", n, reposetup.CodeFrontmatterManualReview)
	}

	path := filepath.FromSlash(findingCatalogPath)
	if *updateCatalog {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatalf("MkdirAll: %v", err)
		}
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatalf("WriteFile %s: %v", path, err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s (regenerate with `go test -count=1 ./internal/app/ -run TestFindingCatalogGolden -update`): %v", path, err)
	}
	if string(want) != got {
		t.Fatalf("%s is out of date; regenerate with `go test -count=1 ./internal/app/ -run TestFindingCatalogGolden -update` and review the diff.\nfresh text:\n%s", path, got)
	}
}
